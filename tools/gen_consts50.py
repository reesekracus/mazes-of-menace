"""Generate web/js/nh50consts.js from a built NetHack 5.0 tree.

Reads the preprocessed src/cmd.c (same flags as the real WASM build), so the
extended-command order and cmap symbol indices match the compiled game exactly.

Usage: python3 tools/gen_consts50.py <cmd.i> <NetHack>/win/share <out.js>
(build50.sh produces cmd.i with `emcc -E` using the build's own flags.)
"""
import json, re, sys

cmd_i, share, out = sys.argv[1:4]
s = open(cmd_i).read()

# extcmdlist[] order = index returned by shim_get_ext_cmd
a = s.index('struct ext_func_tab extcmdlist[] = {')
body = s[a:s.index('};', a)]
# First field is the key: a char literal (may be ',' or '{'), or an expression without commas.
CHAR_LIT = r"""'(?:\\(?:[0-7]{1,3}|x[0-9a-fA-F]+|.)|[^'\\])'"""   # ',' '\0' '\177' '\x1b' ...
rows = re.findall(r"""\{\s*(?:""" + CHAR_LIT + r"""|[^,{}'])+,\s*"([^"]*)",\s*(?:"((?:[^"\\]|\\.)*)")?""", body)
ext = [name for name, _ in rows]
# NetHack's own one-line description of each command, for a touch UI that shows names, not keys.
ext_desc = {name: desc for name, desc in rows if desc}

# enum cmap_symbols: S_* index = glyph_info.gm.sym.symidx for map features (SYM_OFF_P is 0)
m = re.search(r'enum cmap_symbols\s*\{(.*?)\}', s, re.S)
cmap = []
for part in m.group(1).split(','):
    part = re.sub(r'^\s*#.*$', '', part, flags=re.M).strip()
    if part:
        cmap.append(part.split('=')[0].strip())
maxpchars = cmap.index('MAXPCHARS') if 'MAXPCHARS' in cmap else len(cmap)
cmap = cmap[:maxpchars]

# tile names in tilesheet order (monsters, objects, other), for build_tiles and debugging
tiles = []
for name in ('monsters.txt', 'objects.txt', 'other.txt'):
    tiles += re.findall(r'# tile \d+ \(([^)]*)\)', open(f'{share}/{name}').read())

with open(out, 'w') as f:
    f.write('// Generated by tools/gen_consts50.py from the NetHack 5.0.0 build. Do not edit.\n')
    f.write(f'export const EXT_CMDS = {json.dumps(ext)};\n')
    f.write(f'export const EXT_DESC = {json.dumps(ext_desc)};\n')
    f.write(f'export const CMAP = {json.dumps({n: i for i, n in enumerate(cmap)})};\n')
    f.write(f'export const MAXPCHARS = {maxpchars};\n')
    f.write(f'export const TILE_COUNT = {len(tiles)};\n')
print(f'{len(ext)} ext cmds, {maxpchars} cmap symbols, {len(tiles)} tiles -> {out}')
